"""Schematics used by the in-engine tests (mods/sagas/test/mtt.lua).

They are generated by our writer; the Lua tests read them with core.read_schematic, which checks
that Luanti understands what we write. Set SAGAS_WRITE_FIXTURES=1 to regenerate.
"""

import json
import os
from pathlib import Path

import numpy as np
import pytest

from sagas import build, config, palette, schematic
from sagas.voxels import VoxelModel, compute_normals

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / "mods" / "sagas" / "test" / "fixtures"


def box_model() -> VoxelModel:
    X, Y, Z = 7, 5, 7
    m = VoxelModel.empty((X, Y, Z))
    for x in range(X):
        for y in range(Y):
            for z in range(Z):
                wall = x in (0, X - 1) or z in (0, Z - 1) or y == 0
                if z == 0 and x == 3 and y in (1, 2):
                    wall = False
                m.occ[x, y, z] = wall
    m.normal = compute_normals(m.occ)
    return m


def fixtures() -> dict[str, bytes]:
    out: dict[str, bytes] = {}
    meta: dict[str, dict] = {}
    saga = config.parse(
        {
            "id": "box",
            "theme": "sagastest",
            "title": "Box",
            "ruin": {"enabled": True, "debris_height": 2},
            "materials": {"mode": "classes", "default": "stone"},
        },
        Path("x/saga.toml"),
    )
    res = build.build(saga, box_model())
    out["box.mts"] = schematic.to_mts(res.grid)
    meta["box"] = {
        "size": list(res.size),
        "names": res.grid.names,
        "counts": res.grid.counts(),
        "anchor": list(res.anchor),
    }

    # arrow: asymmetric 3x1x2 for rotation checks
    g = schematic.empty((3, 1, 2), ["air", "sagas:color", "sagas:m_brick", "sagas:m_stone"])
    g.content[0, 0, 0] = 3  # stone at local (0,0,0)
    g.content[2, 0, 0] = 2  # brick at local (2,0,0)
    g.content[0, 0, 1] = 1  # colour at local (0,0,1)
    g.param2[0, 0, 1] = 23  # white
    for x, z in ((0, 0), (2, 0), (0, 1)):
        g.param1[x, 0, z] = schematic.PROB_ALWAYS | schematic.FORCE_PLACE
    out["arrow.mts"] = schematic.to_mts(g)
    meta["arrow"] = {"size": [3, 1, 2], "names": g.names, "counts": g.counts()}
    out["expected.json"] = (json.dumps(meta, indent=2, sort_keys=True) + "\n").encode()
    return out


def test_palette_constants_used_by_lua():
    assert palette.load()[251] == "#3aa070"  # materials/minetest_game.lua: emerald -> jade colour node
    assert palette.load()[23] == "#ffffff"


@pytest.mark.skipif(not (ROOT / "mods" / "sagas").is_dir(), reason="not inside the luanti-sagas repository")
def test_fixtures_up_to_date():
    files = fixtures()
    if os.environ.get("SAGAS_WRITE_FIXTURES"):
        FIXTURES.mkdir(parents=True, exist_ok=True)
        for name, data in files.items():
            (FIXTURES / name).write_bytes(data)
    for name, data in files.items():
        assert (FIXTURES / name).read_bytes() == data, f"{name} is stale: run SAGAS_WRITE_FIXTURES=1 pytest"
    g = schematic.read_mts(files["box.mts"])
    assert np.count_nonzero(g.param1) > 0
