"""Scene and shot list for `avanti screenshot mods` (in-game screenshots for ContentDB and the gallery).

Writes mods/tools/showcase/ (a small mod that places every saga in a row on a platform high above
the terrain) and mods/screenshots/shots.json (one camera per saga plus an overview). Both are
excluded from release zips (mods/.gitattributes).
"""

from __future__ import annotations

import json
from pathlib import Path

from .build import BuildResult

Y = 180
GAP = 10

SHOWCASE_LUA = """-- Scene for `avanti screenshot mods`: places every saga listed in layout.json on a platform at
-- y = 180 (above terrain and clouds), then tells avanti_camera the scene is ready. Generated by
-- `sagas build`; inert outside screenshot runs.
if not core.settings:get("avanti_camera_mode") then
	return
end

local layout = core.parse_json(sagas.util.read_file(core.get_modpath(core.get_current_modname()) .. "/layout.json"))

local function floor_node()
	for _, name in ipairs({ "default:stone", "mcl_core:stone" }) do
		if core.registered_nodes[name] then
			return name
		end
	end
	return "sagas:m_rock"
end

core.register_on_joinplayer(function(player)
	local p1 = { x = layout.min[1] - 8, y = layout.min[2] - 2, z = layout.min[3] - 8 }
	local p2 = { x = layout.max[1] + 8, y = layout.max[2] + 2, z = layout.max[3] + 8 }
	core.emerge_area(p1, p2, function(_, _, remaining)
		if remaining > 0 then
			return
		end
		local floor = floor_node()
		local vm = core.get_voxel_manip({ x = p1.x, y = p1.y + 1, z = p1.z }, { x = p2.x, y = p1.y + 1, z = p2.z })
		local emin, emax = vm:get_emerged_area()
		local area = VoxelArea(emin, emax)
		local data = vm:get_data()
		local cid = core.get_content_id(floor)
		for i in area:iterp({ x = p1.x, y = p1.y + 1, z = p1.z }, { x = p2.x, y = p1.y + 1, z = p2.z }) do
			data[i] = cid
		end
		vm:set_data(data)
		vm:write_to_map(true)
		for _, s in ipairs(layout.sagas) do
			sagas.place(
				s.id,
				{ x = s.anchor[1], y = s.anchor[2], z = s.anchor[3] },
				{ rot = 0, foundation = 0, record = false }
			)
		end
		core.set_timeofday(0.5)
		player:set_pos({ x = layout.min[1] - 6, y = layout.max[2] + 4, z = layout.min[3] - 12 })
		local camera = rawget(_G, "avanti_camera")
		if camera then
			camera.scene_ready()
		end
	end)
end)
"""


def write(mods: Path, results: list[BuildResult], check: bool = False) -> list[Path]:
    """Write (or with check=True, only list) the showcase files that differ from a fresh build."""
    results = sorted(results, key=lambda r: (r.saga.theme, r.saga.id))
    x = 0
    sagas = []
    shots = []
    floor_y = Y - 1
    for r in results:
        sx, sy, sz = r.size
        ax, ay, az = r.anchor
        anchor = [x + ax, Y, az]
        sagas.append({"id": r.saga.qualified_id, "anchor": anchor, "size": [sx, sy, sz]})
        cx, cy, cz = x + sx / 2, Y + sy / 2, sz / 2
        d = max(sx, sy, sz) * 1.15 + 6
        shots.append(
            {
                "name": f"{r.saga.theme}-{r.saga.id}",
                "pos": [round(cx - 0.75 * d, 1), round(Y + sy * 0.55 + d * 0.45, 1), round(cz - 1.0 * d, 1)],
                "look_at": [round(cx, 1), round(cy, 1), round(cz, 1)],
                "time": 0.5,
                "fov": 60,
                "settle": 3,
            }
        )
        x += sx + GAP
    if not sagas:
        return []
    width = x - GAP
    height = max(s["size"][1] for s in sagas)
    depth = max(s["size"][2] for s in sagas)
    layout = {"min": [0, floor_y, 0], "max": [width, Y + height, depth], "sagas": sagas}
    shots.insert(
        0,
        {
            "name": "overview",
            "pos": [round(width / 2 - width * 0.25, 1), round(Y + height + width * 0.18, 1), round(-width * 0.45, 1)],
            "look_at": [round(width / 2, 1), round(Y + height / 3, 1), round(depth / 2, 1)],
            "time": 0.5,
            "fov": 70,
            "settle": 4,
        },
    )
    sc = mods / "tools" / "showcase"
    sc.mkdir(parents=True, exist_ok=True)
    out = {
        sc / "mod.conf": "name = sagas_showcase\ndescription = Scene for avanti screenshot (generated)\n"
        "depends = sagas\noptional_depends = avanti_camera, default, mcl_core\n",
        sc / "init.lua": SHOWCASE_LUA,
        sc / "layout.json": json.dumps(layout, indent=1) + "\n",
        mods / "screenshots" / "shots.json": json.dumps({"shots": shots}, indent=1) + "\n",
        mods / ".gitattributes": "# Keep screenshot tooling out of the sagas_pack release zip.\n"
        "/tools export-ignore\n/screenshots export-ignore\n",
    }
    written = []
    for path, text in out.items():
        if path.exists() and path.read_text() == text:
            continue
        written.append(path)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return written
