def _esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def write_site(repo: Repo, results: list[BuildResult], out: Path) -> Path:
    """Static gallery page (GitHub Pages): index.html plus copies of the preview sheets."""
    import shutil

    (out / "previews").mkdir(parents=True, exist_ok=True)
    sagas = {t.name: t for t in repo.sagas()}
    by_saga: dict[str, list[BuildResult]] = {}
    for r in sorted(results, key=lambda r: r.landmark.qualified_id):
        by_saga.setdefault(r.landmark.saga, []).append(r)
    sections = []
    for name, items in by_saga.items():
        t = sagas.get(name)
        cards = []
        for r in items:
            s = r.landmark
            img = ""
            if s.preview_path.exists():
                fname = f"{s.saga}_{s.id}.png"
                shutil.copyfile(s.preview_path, out / "previews" / fname)
                img = f'<img src="previews/{fname}" alt="{_esc(s.title)}" loading="lazy">'
            x, y, z = r.size
            src = f'<a href="{_esc(s.source.url)}">{_esc(s.source.author or "source")}</a>' if s.source.url else ""
            cards.append(
                f'<article class="card">{img}<div><h3>{_esc(s.title)}</h3>'
                f'<div class="meta">{x} x {y} x {z} nodes · {_esc(" or ".join(s.placement.site))}<br>'
                f"{_esc(', '.join(s.placement.biomes))} · 1 per {s.placement.rarity} chunks<br>"
                f"{src} · {_esc(s.source.license)}</div></div></article>"
            )
        title = _esc(t.title if t else name)
        desc = f"<p>{_esc(t.description)}</p>" if t else ""
        sections.append(f'<h2>{title}</h2>{desc}<div class="grid">{"".join(cards)}</div>')
    html = PAGE.format(count=len(results), sagas=len(by_saga), sections="".join(sections))
    (out / "index.html").write_text(html, encoding="utf-8")
    return out / "index.html"


def cdb_long_description(saga: Saga, results: list[BuildResult]) -> str:
    lines = [
        saga.description,
        "",
        "Requires the **sagas** mod. Its landmarks are placed during map generation.",
        "",
        "| Landmark | Size | Where |",
        "|---|---|---|",
    ]
    for r in sorted(results, key=lambda r: r.landmark.id):
        x, y, z = r.size
        lines.append(f"| {r.landmark.title} | {x}x{y}x{z} | {' or '.join(r.landmark.placement.site)} |")
    lines += ["", "Sources and licences: see ATTRIBUTION.md in the package."]
    return "\n".join(lines) + "\n"
