"""Gallery and catalogue: docs/gallery/index.md + catalog.json, and ContentDB long descriptions."""

from __future__ import annotations

import json
import os
from pathlib import Path

from .build import BuildResult
from .repo import Repo, Theme


def card(res: BuildResult, repo: Repo, rel_to: Path) -> dict:
    s = res.saga
    x, y, z = res.size
    preview = s.preview_path
    return {
        "id": s.qualified_id,
        "title": s.title,
        "theme": s.theme,
        "size": [x, y, z],
        "nodes": res.node_count,
        "materials": s.materials.mode,
        "site": s.placement.site,
        "exposure": s.placement.exposure,
        "biomes": s.placement.biomes,
        "rarity": s.placement.rarity,
        "large": s.placement.large,
        "author": s.source.author,
        "license": s.source.license,
        "source_url": s.source.url,
        "ai": s.source.ai,
        "lore": s.lore,
        "preview": os.path.relpath(preview, rel_to) if preview.exists() else None,
    }


def write(repo: Repo, results: list[BuildResult], out_dir: Path | None = None) -> list[Path]:
    out_dir = out_dir or repo.root / "docs" / "gallery"
    out_dir.mkdir(parents=True, exist_ok=True)
    cards = [card(r, repo, out_dir) for r in sorted(results, key=lambda r: r.saga.qualified_id)]
    (out_dir / "catalog.json").write_text(json.dumps(cards, indent=2, ensure_ascii=False) + "\n")
    lines = ["# Sagas gallery", "", "Generated by `sagas catalog`. Each card links the source and its licence.", ""]
    by_theme: dict[str, list[dict]] = {}
    for c in cards:
        by_theme.setdefault(c["theme"], []).append(c)
    themes = {t.name: t for t in repo.themes()}
    for name, items in by_theme.items():
        t = themes.get(name)
        lines += [f"## {t.title if t else name}", ""]
        if t:
            lines += [t.description, ""]
        for c in items:
            x, y, z = c["size"]
            lines += [f"### {c['title']} (`{c['id']}`)", ""]
            if c["preview"]:
                lines += [f"![{c['title']}]({c['preview']})", ""]
            lines += [
                f"- Size: {x} x {y} x {z} nodes, {c['nodes']} nodes, materials: {c['materials']}",
                f"- Placement: {' or '.join(c['site'])}; exposure {c['exposure']}; biomes {', '.join(c['biomes'])}; "
                f"about one per {c['rarity']} mapchunks",
                f"- Source: [{c['author'] or 'unknown'}]({c['source_url']}), {c['license']}",
                "",
            ]
    (out_dir / "index.md").write_text("\n".join(lines))
    return [out_dir / "catalog.json", out_dir / "index.md"]


def cdb_long_description(theme: Theme, results: list[BuildResult]) -> str:
    lines = [
        theme.description,
        "",
        "Requires the **sagas** mod. Sagas are placed during map generation.",
        "",
        "| Saga | Size | Where |",
        "|---|---|---|",
    ]
    for r in sorted(results, key=lambda r: r.saga.id):
        x, y, z = r.size
        lines.append(f"| {r.saga.title} | {x}x{y}x{z} | {' or '.join(r.saga.placement.site)} |")
    lines += ["", "Sources and licences: see ATTRIBUTION.md in the package."]
    return "\n".join(lines) + "\n"
